"""角色属性统计模型定义"""

from typing import final
from pydantic import BaseModel


###############################################################################################################################################
@final
class CharacterStats(BaseModel):
    """简化的角色属性统计，只包含核心战斗属性"""

    # 当前生命值
    hp: int = 0
    # 最大生命值
    max_hp: int = 10
    # 攻击力
    attack: int = 3
    # 防御力
    defense: int = 1
    # 本回合可用行动力（能量）；用于支付出牌/装备等动作费用，耗尽或过牌后本回合不再行动
    energy: int = 2
    # 速度；决定 SPEED_ORDER 策略下的出手优先级，值越大越靠前
    speed: int = 0


###############################################################################################################################################
