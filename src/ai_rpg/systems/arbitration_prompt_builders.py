"""仲裁共享提示词模块。

只保留各类仲裁共用的**计算规则**段落（`build_calc_rules_section`，工具名与仲裁类型
由调用方传入）；广播消息、「生命值已更新」通知、叙事段落等各自在所属仲裁系统文件内定义。
"""

from enum import StrEnum

from ..utils import prompt_builder

#######################################################################################################################################
# 仲裁类型
#######################################################################################################################################


class ArbitrationKind(StrEnum):
    """仲裁类型。

    出牌仲裁与回合结束仲裁的结算原则完全一致，仅「发起阶段」与对行动者的称谓不同；
    本枚举用于让共享的计算规则段落按类型选用正确的称谓（出牌者 / 持有者）。
    """

    PLAY_CARDS = "play_cards"
    TURN_END = "turn_end"


#######################################################################################################################################
# 共享提示词
#######################################################################################################################################


@prompt_builder
def build_calc_rules_section(
    get_entity_stats_tool: str,
    apply_damage_tool: str,
    kind: ArbitrationKind,
) -> str:
    """计算规则段落。

    两个工具名由调用方按各自的 `ToolDefinition` 传入，避免在此硬编码——工具改名时
    只改 `ToolDefinition` 一处，本段自动跟随；`kind` 用于适配对本次结算行动者的称谓。
    """
    actor = "出牌者" if kind is ArbitrationKind.PLAY_CARDS else "持有者"
    return f"""## 计算规则（全局骨架）

一次结算含 `hit_count` 次命中，**每次命中各算一次**；所有伤害结算都套用这条骨架，骨架之外不引入新机制。

### 参数（全由词缀 / 神器文案指导取值；未提及即取默认）

本卡 `on_play_affixes`、目标的 `on_hit_affixes`、神器 `modifiers` 等文案，用来指导你判定下列参数：

- **伤害系数**（默认 1）：调整本卡 `damage`。词缀可要求你**结合对手状态或设定**上调，例如「对动物属性 +50%」「目标带某词缀/标记时×2」——此时应结合已知的外观 / 人设等信息自行判定取值；
- **格挡系数**（默认 1）：调整目标「总格挡」的抵扣；
- **反伤**（默认 0）：目标（或其手牌 `on_hit_affixes` 等）对本次{actor}的反噬，**每次命中各结算一次**，使 {actor} 的 HP **减少**（不过总格挡）；
- **吸血 / 治疗**（默认 0）：本卡等对 {actor} 的回复，**每次命中各结算一次**，使 {actor} 的 HP **增加**。

上述参数凡取**非默认值**，都须在 combat_log 里注明**取值依据**（如 `[对动物属性 伤害系数2]`、`[护喉 反伤2]`）。
一切数值只取本次 `{get_entity_stats_tool}` 返回与卡牌字段，禁止引用历史 / 前几回合广播 / 记忆。

### 单次命中（共 hit_count 次）

每次命中：`命中伤害 = max(0, 本卡 damage × 伤害系数 − 该目标总格挡 × 格挡系数)`；同时各结算一次 本次反伤 / 本次吸血 / 本次治疗。

### 合计与落账

`本卡合计伤害 = Σ 命中伤害`；`合计反伤 = 反伤 × hit_count`；`合计吸血 = 吸血 × hit_count`；`合计治疗 = 治疗 × hit_count`。
（若某条词缀明确写「打出时一次性」之类的单发效果，则该项只计 1 次，依词缀文案。）

对每个受影响角色，先算出它本次的**净扣减 `amount`**（= 该角色承受的伤害 − 该角色获得的回复；正数扣血、负数净回复、0 不变），再调用一次 `{apply_damage_tool}` 写入（工具自动 clamp 到 0~最大 HP）：

- 目标：`amount = 本卡合计伤害`
- {actor}：`amount = 合计反伤 − 合计吸血 − 合计治疗`

### 硬约束

- 只有「本卡合计伤害」用来扣目标 HP，它就是 combat_log 里的「伤害 Z」（＝目标 HP 减少量，旧−新）。
- **「本卡合计伤害」> 0 时，目标 HP 必须按此减少**；不存在「被挡下 / 实际扣减 0」——只有当合计伤害恰为 0 时 HP 才不变。
- 每个受影响角色都要调一次 `{apply_damage_tool}`；combat_log 里的「伤害 Z」必须与工具返回的「本次扣减 Z」**逐字一致**，对不上即算错，须重算后再提交。
- 「总格挡」是角色级数值（其手牌 `block` 之和），不是单牌 `block`。
- {actor} 当前 HP 为 0 时跳过结算（日志记「已阵亡，卡牌无法执行」）。

**算例**：本卡 damage=6、hit_count=2、无词缀（伤害系数 1、格挡系数 1、反伤 0），目标 HP 20、总格挡 4 → 每次命中 `max(0,6−4)=2`，合计 4，目标 20→16；若本卡词缀使伤害系数=2，则每次命中 `max(0,12−4)=8`，合计 16，目标 20→4；若目标另有反伤 3/击，则 {actor} 被反伤 `3×2=6`。"""
