# ---------------------------------------------------------------------------
# CAMPAIGN_SETTING 编写原则
# ---------------------------------------------------------------------------
# 定位：注入到每个实体（actor / stage / world system）system prompt 的
#       「游戏设定」段，是全部实体的最低公共知识——战役的大背景。
#
# 应包含：
#   - 类型标签（赛博朋克），决定 LLM 的语体与意象库
#   - 城市锚点（新香港），约束所有实体对"当下世界"的默认感知
#   - 双层面存在（现实 / 网络空间），使 LLM 在 Home↔Dungeon 穿梭时不会因
#     环境剧变而认知断裂——不暴露具体地点与真假关系，仅告知"这是正常的"
#   - 核心玩法支柱（接单 / 深潜 / 编写程序），让实体理解玩家行为的基本范式
#
# 不应包含：
#   - 具体地点（来世、城寨）——由各自 profile 赋予；「墙外」为世界专属认知，不注入 actor/stage/item
#   - 阵营信息、势力关系、结局方向——属于叙事层，非公共知识
#   - 任何"这个世界的真相是……"式的解释性陈述
#
# 副本=网络空间（深潜）的语义不写在这里，而是写在独立的 DUNGEON_RULES 常量中，
# 与内容无关的 SYSTEM_RULES 拼接为 SYSTEM_RULES_FINAL 后注入——
# 它不属于战役大背景，而是随全局规则一并下发。
#
# 原则：一个刚苏醒的失忆黑客读了这段，只知道自己所处的世界和氛围，
#       不会知道任何具体地点、阵营或势力关系。
# ---------------------------------------------------------------------------


