# ---------------------------------------------------------------------------
# 定位：通过 ChromaDB 注入为公共记忆（RAG），任何角色发起 QueryAction
#       均可检索。是"这个世界里任何一个路人可能知道的事"。
#
# 应包含：
#   - 客观环境事实（建筑外观、气候、气味），仅感官层面
#   - 任何人站在该处都能观察到的信息
#
# 不应包含：
#   - 人物信息（医师、护工、病友）——人物由各自 profile 承载
#   - 解释性判断（"这里是认知的囚笼"）
#   - 跨世界信息（"大傩是真实的猎场"）
#   - 阵营立场、叙事秘密、核心矛盾
#
# 原则：如果一条信息需要"特定身份"或"特定认知阶段"才能知晓，
#       就不应该出现在这里。
#
# 数量控制：条目越多，RAG 检索噪声越大。优先控制在 5 条以内。
# ---------------------------------------------------------------------------


