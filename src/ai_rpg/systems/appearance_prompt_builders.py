"""外观合成提示词工具函数。"""

from ..utils import prompt_builder


#######################################################################################################################################
@prompt_builder
def build_wear_costume_message(
    entity_name: str, costume_name: str, new_appearance: str
) -> str:
    """构建穿上时装后的外观更新消息。"""
    return f"# {entity_name} 的外观已更新\n{entity_name} 穿上了「{costume_name}」。\n当前外观：{new_appearance}"


#######################################################################################################################################
@prompt_builder
def build_remove_costume_message(entity_name: str, base_body: str) -> str:
    """构建脱下时装后的外观更新消息。"""
    return f"# {entity_name} 的外观已更新\n时装已移除，外观恢复为基础体型。\n当前外观：{base_body}"


#######################################################################################################################################
@prompt_builder
def build_appearance_synthesis_prompt(
    base_body: str,
    costume_name: str,
    costume_description: str,
) -> str:
    """构建外观合成提示词（面向文生图：输出客观、静态、可观察的第三人称外观描述）。"""
    return f"""# 任务：合成「{costume_name}」穿戴后的角色外观描述

基础体型：{base_body}
时装「{costume_name}」描述：{costume_description}

把两者合并成一段第三人称的客观视觉描述，只写肉眼可见的静态事实（身形、肤色、发色发型、面部、疤痕、姿态、服饰的颜色/材质/款式/磨损/穿法、随身装备）：

- 时装遮挡处不写；未遮挡处保留基础体型原貌（宽松衣物不改变骨架与体态）。
- 中性平实的陈述句：不写心理/情绪/意图，不作评价或身份推断，不用比喻，不写来历与遭遇。
- 不引入场景、环境、光线、天气、同行者或当下之事，也不与其他对象比较；不写「风起时」这类依赖外部条件的动态。
- 不写气味、声音、触感；信息缺失就直接省略，不写「未详/不明」。
- 若基础体型或时装描述混有以上主观成分，只提取可观察的外形事实。
- 篇幅不少于基础体型，与其相当或略长。

只输出外观描述本身，不要解释。"""


