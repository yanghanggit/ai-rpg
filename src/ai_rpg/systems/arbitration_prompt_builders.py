"""仲裁共享提示词模块。

只保留各类仲裁共用的**计算规则**段落（`build_calc_rules_section`，工具名与仲裁类型
由调用方传入）；广播消息、「生命值已更新」通知、叙事段落等各自在所属仲裁系统文件内定义。
"""

from enum import StrEnum

from ..utils import prompt_builder

#######################################################################################################################################
# 仲裁类型
#######################################################################################################################################


class ArbitrationKind(StrEnum):
    """仲裁类型。

    出牌仲裁与回合结束仲裁的结算原则完全一致，仅「发起阶段」与对行动者的称谓不同；
    本枚举用于让共享的计算规则段落按类型选用正确的称谓（出牌者 / 持有者）。
    """

    PLAY_CARDS = "play_cards"
    TURN_END = "turn_end"


#######################################################################################################################################
# 共享提示词
#######################################################################################################################################


@prompt_builder
def build_calc_rules_section(
    get_entity_stats_tool: str,
    set_entity_hp_tool: str,
    kind: ArbitrationKind,
) -> str:
    """计算规则段落。

    两个工具名由调用方按各自的 `ToolDefinition` 传入，避免在此硬编码——工具改名时
    只改 `ToolDefinition` 一处，本段自动跟随；`kind` 用于适配对本次结算行动者的称谓。
    """
    actor = "出牌者" if kind is ArbitrationKind.PLAY_CARDS else "持有者"
    return f"""## 计算规则

- **总格挡**：只取本次 `{get_entity_stats_tool}` 返回的、**该角色自己的**「总格挡」（角色级数值＝其手牌 block 之和）。卡牌字段 `block` 是**单牌格挡**，与「总格挡」不是一回事。结算某个目标的伤害时，只减**该目标的总格挡**；不得改用{actor}或任何其它角色的总格挡，不得再叠加单牌格挡，也不得凭记忆 / 历史广播补算。
- **词缀字段**：词缀里的 `damage` / `hit_count` / `block` 均指**本卡**的对应字段。

### 结算（对每个受到影响的目标各算一次）

1. **基础段**：共 `hit_count` 段，每段 `max(0, 本卡 damage − 该目标总格挡)`，各段求和。
2. **词缀段**：本卡每一条词缀各自成一项，逐条写出「`<词缀原文>` → 追加 <?>」并求和；词缀追加的伤害 / 格挡不再过总格挡，直接并入求和。**一条都不能漏，漏一条即算错。**
3. **净伤害 = 基础段之和 + 词缀段之和**；`最终 HP = clamp(当前 HP − 净伤害, 0, 最大 HP)`。

> ⚠️ **只有「净伤害」用来扣血**，它就是 `combat_log` 里的「伤害 Z」（＝目标 HP 减少量）。`damage × hit_count + 词缀追加` 这个**未减总格挡的原始和不是扣血量**，不要拿它去减 HP。

### 硬约束

- 一切数值只取本次 `{get_entity_stats_tool}`，禁止引用历史 / 前几回合广播 / 记忆。
- 净伤害 > 0 时 HP 必减（不存在「未破防 / 被挡下大半」）；恰为 0 时才不变。
- `combat_log` 的「伤害 Z」= 目标 HP 减少量（旧−新），且与 `{set_entity_hp_tool}` 写入值一致；对不上即算错，须重算后再提交。
- {actor}当前 HP 为 0 时跳过结算（日志记「已阵亡，卡牌无法执行」）。

**算例**：本卡 damage=6、hit_count=2、无词缀，目标 HP 20、总格挡 4 → 每段 `max(0,6−4)=2`，两段合计 4，净伤害 4，最终 HP 16，记 `HP:目标 20→16`；若本卡另有词缀「追加 damage×1」，则词缀段再追加 6，净伤害 10，最终 HP 10。"""
