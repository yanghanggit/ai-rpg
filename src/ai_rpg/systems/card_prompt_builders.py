"""Card 构造提示词构建器模块"""

from typing import Final
from ..models import TargetType


#######################################################################################################################################
BUILD_CARD_FIELD_DESCRIPTION: Final[
    str
] = f"""## 卡牌字段说明

| 字段 | 说明 |
|---|---|
| name | 卡牌名称（≤8字），富有想象力，体现行动意图 |
| description | 第三人称，客观描述卡牌对应的战斗行为（不含数值，不重述数值字段已确定的效果） |
| affixes | 延迟词缀列表；**每个元素必须是单个字符串**（禁止输出 `{{"name": ..., "description": ...}}` 这样的对象），格式为 `名称:触发倾向描述`，例如 `"呛咳:呼吸不畅，下回合手牌伤害-2"`；出牌后独立推理生成持续状态效果；凡涉及"下回合/持续N回合/未来生效"等跨回合影响的效果（如手牌数值削弱、致盲、压制、禁锢等）必须放在这里；本游戏为回合制，禁止出现"命中率""闪避"等基于概率的判定机制；无则 [] |
| modifiers | 即时修正词缀列表；**每个元素必须是单个字符串**（禁止输出 `{{"name": ..., "description": ...}}` 这样的对象），格式为 `名称:即时修正描述`，例如 `"无视防御:本次攻击无视目标防御"`；仅描述**本次**仲裁计算内立即生效、一次性叠加的数值修正（如无视防御、伤害加成），严禁出现"下回合/持续N回合"等跨回合表述；无则 [] |
| playable | 是否可出牌；默认 true |
| exhaust | 出牌后是否永久消耗（归入消耗堆）；默认 false |
| cost | 出牌费用，消耗行动者当前 energy 点数；默认 1；多数卡应为 1，仅显著强力/多段/高价值效果卡可设为 2；纯功能性/无实质收益卡可设为 0 |
| damage_dealt | 单次命中造成的伤害（以角色攻击力为基数计算；无伤害取 0） |
| energy_delta | 改变目标行动次数（正值增加，负值剥夺）；默认 0 |
| hit_count | 攻击次数（默认 1；多段可设 2~4，每段独立作用） |
| target_type | 出牌目标类型（见下表） |

| target_type | 含义 |
|---|---|
| `{TargetType.SINGLE}` | 作用于单个存活角色（可为敌方造成伤害，也可为友方治疗/增益，依卡牌效果自行选择合理目标，默认） |
| `{TargetType.ALL}` | 选定一个目标作为阵营锚点，实际作用于其所在阵营的全部存活角色（选敌方角色=攻击全体敌方；选己方角色=治疗/增益全体己方） |
| `{TargetType.SPREAD}` | 选定一个目标作为阵营锚点，对其所在阵营全体存活角色散射攻击：hit_count 大于该阵营人数时保证每人至少命中一次，多余次数随机；否则纯随机（可能重复或遗漏） |
| `{TargetType.SELF}` | 仅作用于自身（防御、自损诅咒等） |"""


