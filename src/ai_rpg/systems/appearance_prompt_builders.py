"""外观合成提示词工具函数。"""

from ..utils import prompt_builder


#######################################################################################################################################
@prompt_builder
def build_wear_costume_message(
    entity_name: str, costume_name: str, new_appearance: str
) -> str:
    """构建穿上时装后的外观更新消息。"""
    return f"# {entity_name} 的外观已更新\n{entity_name} 穿上了「{costume_name}」。\n当前外观：{new_appearance}"


#######################################################################################################################################
@prompt_builder
def build_appearance_synthesis_prompt(
    base_body: str,
    costume_name: str,
    costume_description: str,
) -> str:
    """构建外观合成提示词（面向文生图：输出客观、静态、可观察的第三人称外观描述）。"""
    return f"""# 任务：合成「{costume_name}」穿戴后的角色外观描述

基础体型：{base_body}
时装「{costume_name}」：{costume_description}

把两者融合成一段中性的第三人称陈述句：只写肉眼可见的静态外形事实，篇幅不短于基础体型；只输出该描述，不要解释。

- 覆盖维度：身形/肤色/发色发型/面部/疤痕/姿态/服饰（颜色/材质/款式/磨损/穿法）/随身装备。
- 以基础体型为底：时装覆盖处不写、不推测衣物下的身体；未覆盖处保留基础体型原貌，宽松衣物不改变骨架体态。
- 不写主观（心理/情绪/意图/评价/身份推断/比喻/来历/遭遇）、场景（环境/光线/天气/同伴/当下事件）、比较、依赖外部条件的动态（如「风起时」）、气味/声音/触感。
- 输入中的主观成分只提取可观察事实；信息缺失即省略，不写「未详/不明」。"""


