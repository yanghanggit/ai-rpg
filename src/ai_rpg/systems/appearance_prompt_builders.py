"""外观合成提示词工具函数。"""


#######################################################################################################################################
def build_wear_costume_message(
    entity_name: str, costume_name: str, new_appearance: str
) -> str:
    """构建穿上时装后的外观更新消息。"""
    return f"# {entity_name} 的外观已更新\n{entity_name} 穿上了「{costume_name}」。\n当前外观：{new_appearance}"


#######################################################################################################################################
def build_remove_costume_message(entity_name: str, base_body: str) -> str:
    """构建脱下时装后的外观更新消息。"""
    return f"# {entity_name} 的外观已更新\n时装已移除，外观恢复为基础体型。\n当前外观：{base_body}"


#######################################################################################################################################
def build_appearance_synthesis_prompt(
    base_body: str,
    costume_name: str,
    costume_description: str,
) -> str:
    """构建外观合成提示词。"""
    return f"""# 你刚刚穿上了时装「{costume_name}」。

基础体型：{base_body}
时装「{costume_name}」描述：{costume_description}

时装可能覆盖或遮挡身体的某些部分（如上衣覆盖躯干、长裙遮住腿部），但未覆盖的部分——面部、颈部、手部、身形轮廓、性别特征等——应保留基础体型中的描述。宽松衣物并不隐藏穿着者的骨架与体态。
请综合推理穿戴后的真实视觉效果，用第三人称写一段简短的外观描述（不超过50字）。
只输出外观描述本身，不要解释。"""


