"""Card 构造提示词构建器模块"""

from typing import Final
from ..models import TargetType


#######################################################################################################################################
BUILD_CARD_FIELD_DESCRIPTION: Final[
    str
] = f"""## 卡牌字段说明

| 字段 | 说明 |
|---|---|
| name | 卡牌名称，≤8 字，体现核心意象 |
| description | 叙事锚点：围绕叙事主题展开；不含数值，不重述其它字段已确定的效果 |
| on_play_affixes | 即时词缀；字符串列表；格式 `[名称]:触发倾向描述`；仅本次出牌结算生效，不落地状态效果；无则 [] |
| on_hit_affixes | 受击词缀；字符串列表；格式 `[名称]:触发倾向描述`；持有期间生效，持有者被命中时触发；无则 [] |
| on_turn_end_affixes | 回合结束词缀；字符串列表；格式 `[名称]:触发倾向描述`；持有期间在回合结束（pass turn）时触发；无则 [] |
| playable | 是否可出牌；默认 true |
| exhaust | 出牌后永久消耗，不进抽牌循环；默认 false |
| retain | 回合末保留在手牌，不进弃牌堆；默认 false |
| ethereal | pass turn 时若仍在手牌则自动消耗；默认 false |
| cost | 出牌费用，消耗 energy；默认 1 |
| damage | 单次伤害；非 0 叠加角色攻击力；无伤害取 0 |
| hit_count | 攻击次数；默认 1，多段各自独立 |
| block | 持有期格挡，累加进持有者防御；非 0 叠加角色防御力；无格挡取 0 |
| self_target | 锁定自身；true 时无需 targets |
| target_type | 目标类型；self_target=true 时忽略 |

| target_type | 含义 |
|---|---|
| `{TargetType.SINGLE}` | 单个存活角色（默认） |
| `{TargetType.ALL}` | 阵营锚点，作用于该阵营全部存活角色 |
| `{TargetType.SPREAD}` | 阵营锚点，散射该阵营存活角色；hit_count 超过人数时每人至少一次，多余随机；否则纯随机 |"""


