"""游戏状态校验失败的领域异常。

供 API 与后台任务共享的前置条件校验使用：不依赖 HTTP，由
``room_error_handlers`` 统一映射为响应。
"""


###############################################################################################################################################
class GameStateError(Exception):
    """游戏状态不满足操作前置条件。"""

    status_code: int = 400
    detail: str = "游戏状态非法"

    def __init__(self, *, user_name: str = "") -> None:
        super().__init__(self.detail)
        self.user_name: str = user_name


###############################################################################################################################################
class GameNotFoundError(GameStateError):
    """玩家没有游戏实例。"""

    status_code = 404
    detail = "没有游戏，请先登录"


###############################################################################################################################################
class PlayerNotAtHomeError(GameStateError):
    """玩家不处于家园状态。"""

    status_code = 400
    detail = "当前不在家园状态，不能进行家园操作"
