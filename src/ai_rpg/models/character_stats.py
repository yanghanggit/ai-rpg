"""角色属性统计模型定义"""

from typing import final

from pydantic import BaseModel


###############################################################################################################################################
@final
class CharacterStats(BaseModel):
    """简化的角色属性统计，只包含核心战斗属性"""

    # 当前生命值
    hp: int = 10
    # 最大生命值
    max_hp: int = 10
    # 攻击力
    attack: int = 3
    # 防御力
    defense: int = 1
    # 速度：决定回合行动顺序，数值越大越先出手；相同则按实体创建顺序
    speed: int = 0


###############################################################################################################################################
