@prompt_builder
def build_arbitration_broadcast(
    combat_log: str, narrative: str, current_round_number: int, title: str
) -> str:
    """仲裁广播消息生成器（三类仲裁共用）。"""
    return f"""# 第 {current_round_number} 回合 · {title}

## 演出

{narrative}

## 数据日志

{combat_log}"""
