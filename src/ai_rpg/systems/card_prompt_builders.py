"""Card 构造提示词构建器模块"""

from typing import Final
from ..models import TargetType


#######################################################################################################################################
BUILD_CARD_FIELD_DESCRIPTION: Final[
    str
] = f"""## 卡牌字段说明

| 字段 | 说明 |
|---|---|
| name | 卡牌名称（≤8字），体现本卡的核心意象 |
| description | 本卡的叙事锚点：围绕「叙事主题」展开，可自由采用动作、物件、意象、氛围、典故等任意形态（不含数值，不重述数值字段已确定的效果） |
| on_play_affixes | 即时词缀列表；**每个元素必须是单个字符串**（禁止输出对象），格式为 `名称:触发倾向描述`（如 `[穿透]:本次伤害无视目标防御`）；参与本卡本次出牌仲裁、仅对本次结算生效，不落地状态效果；只放本次出牌即时生效的特殊规则；无则 [] |
| playable | 是否可出牌；默认 true |
| exhaust | 出牌后是否永久消耗（本场战斗不再进入抽牌循环）；默认 false |
| cost | 出牌费用，消耗行动者当前 energy 点数；默认 1 |
| damage | 单次命中造成的伤害（以角色攻击力为基数计算；无伤害取 0） |
| hit_count | 攻击次数（默认 1；多段时每段独立作用） |
| target_type | 出牌目标类型（见下表） |

| target_type | 含义 |
|---|---|
| `{TargetType.SINGLE}` | 作用于单个存活角色（默认） |
| `{TargetType.ALL}` | 选定一个目标作为阵营锚点，作用于其所在阵营的全部存活角色 |
| `{TargetType.SPREAD}` | 选定一个目标作为阵营锚点，对其所在阵营全体存活角色散射：hit_count 大于该阵营人数时保证每人至少一次，多余次数随机；否则纯随机（可能重复或遗漏） |
| `{TargetType.SELF}` | 仅作用于自身 |"""


