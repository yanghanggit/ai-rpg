CARD_NARRATIVE_DESCRIPTION: Final[
    str
] = """### narrative

60-120 字，第三人称外部视角，纯感官描写，无数字 / 术语 / 内心。
以本次结算所用卡牌的「叙事（description）」为素材，把卡牌意象延展成一段外部可见的动作或现象；不得引入卡牌与其词缀之外的机制。
若卡牌效果改变了某个人或物的状态，描写须体现这一改变，为后续叙事留下可推断的当前状态。"""


CALC_RULES_SECTION: Final[
    str
] = """## 计算规则

**卡牌出牌**：单段有效伤害 = max(0, damage − 目标格挡)，共 hit_count 段；出牌者 HP 为 0 则跳过结算。
**格挡**：目标格挡一律以 `get_entity_stats` 返回的 `BLOCK` 字段为准（该角色手牌 block 之和）。**直接使用该值，禁止再叠加任何手牌 block，也禁止从对话历史/记忆补算格挡**。
**词缀字段引用**：词缀的机械结算描述会显式引用字段——`damage` 指本卡 damage 字段、`block` 指本卡 block 字段、`hit_count` 指本卡攻击次数；`×N` 表示对该字段值取 N 倍。词缀若提及「非 source 者」，指当前持有者（当其不等于该卡 `source` 时，如可转移牌投递给他人）。词缀造成的伤害/格挡一律以上述字段与倍率为准，不得另造数值，也不得忽略词缀显式写出的字段。
**数据来源**：结算所需的一切数值只允许来自本次 `get_entity_stats` 的返回结果；禁止引用对话历史、前几回合广播或记忆中的任何卡牌、block 或数值。
**叙事泛化**：将「描述/叙事」作为 narrative 的素材，结合场景环境、状态效果自由泛化，但不得改变以上结算规则确定的数值结果。

目标 HP = max(0, min(计算后 HP, 最大 HP))"""


