"""角色属性统计模型定义"""

from typing import final
from pydantic import BaseModel


###############################################################################################################################################
@final
class CharacterStats(BaseModel):
    """简化的角色属性统计，只包含核心战斗属性"""

    # 当前生命值
    hp: int = 15
    # 最大生命值
    max_hp: int = 15
    # 攻击力
    attack: int = 3
    # 防御力
    defense: int = 1


